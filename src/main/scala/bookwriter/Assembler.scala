package bookwriter

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path}
import java.time.Duration
import java.time.LocalDate
import zio.json._

object Assembler {

  def markdown(
    outline: BookOutline,
    chapters: List[WrittenChapter],
    foreword: String,
    blurb: String,
    cfg: Config,
    elapsed: Duration
  ): String = {
    val sections = List(
      frontMatter(outline, blurb, cfg).mkString("\n"),
      quotedSection("Foreword", foreword),
      contents(chapters),
      chapterSections(chapters)
    ).filter(_.nonEmpty)

    (sections.mkString("\n\n---\n\n") + "\n" + footer(outline, chapters, elapsed)).trim + "\n"
  }

  /** Scholar mode: abstract front matter, sections, references, then the fact-check
    * and peer-review reports as appendices. */
  def scholarMarkdown(
    outline: BookOutline,
    chapters: List[WrittenChapter],
    refs: List[Reference],
    findings: List[Finding],
    review: Option[ReviewReport],
    cfg: Config,
    elapsed: Duration
  ): String = {
    val sections = List(
      scholarFrontMatter(outline, refs, cfg).mkString("\n"),
      contents(chapters),
      chapterSections(chapters),
      referencesSection(refs),
      factCheckAppendix(findings),
      reviewAppendix(review)
    ).filter(_.nonEmpty)

    (sections.mkString("\n\n---\n\n") + "\n" + footer(outline, chapters, elapsed)).trim + "\n"
  }

  private def frontMatter(outline: BookOutline, blurb: String, cfg: Config): Vector[String] =
    Vector(
      s"# ${outline.title}",
      "",
      if (outline.genre.isEmpty) "" else s"**${outline.genre}**\n",
      s"*Generated by book-writer (loki-engine, ${cfg.model}) on ${LocalDate.now()}*",
      "",
      if (blurb.isEmpty) "" else blurb.linesIterator.map("> " + _).mkString("\n")
    )

  private def scholarFrontMatter(outline: BookOutline, refs: List[Reference], cfg: Config): Vector[String] =
    Vector(
      s"# ${outline.title}",
      "",
      if (outline.genre.isEmpty) "" else s"**${outline.genre}**\n",
      s"*Generated by book-writer scholar mode (loki-engine, ${cfg.model}) on ${LocalDate.now()} · ${refs.size} references*",
      "",
      "## Abstract",
      "",
      outline.premise.trim
    )

  private def referencesSection(refs: List[Reference]): String =
    if (refs.isEmpty) ""
    else
      "## References\n\n" + refs.map(_.format).mkString("\n\n")

  private def factCheckAppendix(findings: List[Finding]): String =
    if (findings.isEmpty) ""
    else {
      val majors = findings.count(f => f.isMajor || f.verdict == "contradicted" || f.verdict == "unsupported")
      val rows = findings.map { f =>
        val cited = if (f.citations.isEmpty) "—" else f.citations
        s"| ${f.section} | ${escapeCell(f.claim)} | $cited | ${f.verdict} | ${f.severity} | ${escapeCell(f.note)} |"
      }.mkString("\n")
      s"""## Appendix A — Fact-check report
|
|Cross-check of claims against the reference list: ${findings.size} claims examined, $majors problems found.
|
|| § | Claim | Cited | Verdict | Severity | Note |
||---|---|---|---|---|---|
|$rows"""
    }

  private def reviewAppendix(review: Option[ReviewReport]): String =
    review match {
      case None => ""
      case Some(r) =>
        val issues =
          if (r.issues.isEmpty) "None."
          else
            r.issues.map(i => s"- **§${i.section} [${i.severity}]** ${i.comment}").mkString("\n")
        s"""## Appendix B — Peer review
|
|**Verdict:** ${r.verdict} · **Score:** ${r.score}/10
|
|${r.summary}
|
|### Issues
|
|$issues"""
    }

  private def escapeCell(s: String): String =
    s.replace("|", "\\|").replace("\n", " ")

  private def quotedSection(heading: String, body: String): String =
    if (body.trim.isEmpty) "" else s"## $heading\n\n${body.trim}"

  private def contents(chapters: List[WrittenChapter]): String =
    "## Contents\n\n" + chapters.map(c => s"${c.plan.number}. ${c.plan.title}").mkString("\n")

  private def chapterSections(chapters: List[WrittenChapter]): String =
    chapters.map { c =>
      s"## Chapter ${c.plan.number} — ${c.plan.title}\n\n${c.text.trim}"
    }.mkString("\n\n---\n\n")

  private def footer(outline: BookOutline, chapters: List[WrittenChapter], elapsed: Duration): String = {
    val totalWords = chapters.map(_.wordCount).sum
    val mins = elapsed.getSeconds / 60
    val secs = elapsed.getSeconds % 60
    s"*${totalWords} words · ${chapters.size} chapters · generated in ${mins}m ${secs}s*"
  }

  def save(
    cfg: Config,
    md: String,
    outline: BookOutline,
    chapters: List[WrittenChapter],
    refs: List[Reference] = Nil,
    findings: List[Finding] = Nil,
    review: Option[ReviewReport] = None
  ): List[Path] = {
    val outPath = cfg.out.toAbsolutePath.normalize
    val parent = outPath.getParent
    Files.createDirectories(parent)

    Files.writeString(outPath, md, StandardCharsets.UTF_8)

    val stem = outPath.getFileName.toString.stripSuffix(".md").stripSuffix(".markdown")
    val outlinePath = parent.resolve(s"$stem-outline.json")
    Files.writeString(outlinePath, outline.toJson, StandardCharsets.UTF_8)

    val chaptersDir = parent.resolve(s"$stem-chapters")
    Files.createDirectories(chaptersDir)
    val chapterPaths = chapters.map { c =>
      val name = f"ch-${c.plan.number}%02d-${slug(c.plan.title)}.md"
      Files.writeString(chaptersDir.resolve(name), c.text.trim + "\n", StandardCharsets.UTF_8)
      chaptersDir.resolve(name)
    }

    val scholarPaths =
      if (refs.isEmpty) Nil
      else {
        val refsPath = parent.resolve(s"$stem-references.json")
        Files.writeString(refsPath, refs.toJson, StandardCharsets.UTF_8)

        val reportPath = parent.resolve(s"$stem-scholar-report.md")
        val report = List(factCheckAppendix(findings), reviewAppendix(review)).filter(_.nonEmpty)
        if (report.nonEmpty)
          Files.writeString(reportPath, "# Scholar report\n\n" + report.mkString("\n\n") + "\n", StandardCharsets.UTF_8)
        List(refsPath) ++ (if (report.isEmpty) Nil else List(reportPath))
      }

    List(outPath, outlinePath) ++ chapterPaths ++ scholarPaths
  }

  def slug(s: String): String = {
    val cleaned = s.toLowerCase.replaceAll("[^a-z0-9]+", "-")
      .stripPrefix("-").stripSuffix("-")
    if (cleaned.isEmpty) "untitled" else cleaned.take(60)
  }
}
